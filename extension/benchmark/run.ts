/**
 * Run the benchmark and write the report.
 *
 * `npm run benchmark`. Prints to the console and rewrites docs/BENCHMARK.md, so
 * the numbers in the repository are generated rather than typed — a hand-copied
 * figure is one refactor away from being a lie, and this is the one document
 * whose entire purpose is being true.
 *
 * WHAT THIS EXERCISES
 *
 * `detectDomPii` on real element maps: the DOM rules, the Indian identifier
 * rules and the content classifier, which is where all of metric 2 lives for
 * text and fields. It does NOT exercise capture, OCR or face detection — those
 * need a browser, and measuring them needs pixel ground truth rather than
 * element labels. Their absence is stated in the report rather than left for a
 * reader to assume the number covers everything.
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { detectDomPii } from '../src/lib/pii/dom-rules';
import { ocrRegions } from '../src/lib/pii/ocr-regions';
import {
  PIXEL_IOU,
  scoreByCategory,
  scorePage,
  scorePixels,
  summarise,
} from '../src/lib/benchmark/score';
import type {
  BenchmarkReport,
  PixelScore,
  ScoredDetection,
} from '../src/lib/benchmark/score';
import { CORPUS, captureProblems } from './corpus';
import { PIXEL_READINGS } from './pixels';

const REPORT_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
  'docs',
  'BENCHMARK.md',
);

function percent(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

function ratio(value: number): string {
  return `${value.toFixed(2)}x`;
}

/**
 * What the visual path finds on one document, given perfect recognition.
 *
 * The real `ocrRegions` over word boxes taken from the committed sample SVGs.
 * It measures everything downstream of the engine — line grouping, the shared
 * classifier, box placement — and nothing about the engine itself, which cannot
 * run here. That distinction is printed in the report rather than left for a
 * reader to assume the number covers both.
 *
 * The element id is dropped on the way out. These are being scored against
 * boxes on a card, not against an element label, and `scorePixels` takes only
 * detections with no element precisely so the two paths cannot count the same
 * finding twice.
 */
function pixelDetections(pageId: string): ScoredDetection[] {
  const reading = PIXEL_READINGS[pageId];
  if (!reading) return [];

  const candidate = {
    elementId: 'card',
    x: 0,
    y: 0,
    width: reading.width,
    height: reading.height,
  };

  return ocrRegions(
    { elementId: 'card', words: reading.words },
    candidate,
    reading.width,
    reading.height,
  ).map((region) => ({
    elementId: null,
    category: region.category,
    position: region.position,
  }));
}

function build(): BenchmarkReport {
  const scored = CORPUS.map((page) => {
    const detections: ScoredDetection[] = detectDomPii(page.input).map((region) => ({
      elementId: region.elementId,
      category: region.category,
      position: region.position,
    }));

    return { page, detections };
  });

  const pixels: PixelScore[] = CORPUS.filter(
    (page) => page.pixels && PIXEL_READINGS[page.id],
  ).map((page) => scorePixels(page, pixelDetections(page.id)));

  return summarise(
    scored.map(({ page, detections }) => scorePage(page, detections)),
    scoreByCategory(scored),
    pixels,
  );
}

/** Pages carrying pixel boxes that nothing has been able to read yet. */
function unmeasuredPixelPages(): { id: string; boxes: number }[] {
  return CORPUS.filter((page) => page.pixels && !PIXEL_READINGS[page.id]).map((page) => ({
    id: page.id,
    boxes: page.pixels?.length ?? 0,
  }));
}

function sourceCounts(): { source: string; pages: number }[] {
  const counts = new Map<string, number>();
  for (const page of CORPUS) counts.set(page.source, (counts.get(page.source) ?? 0) + 1);
  return [...counts].map(([source, pages]) => ({ source, pages })).sort((a, b) => b.pages - a.pages);
}

function markdown(report: BenchmarkReport): string {
  const { overall } = report;
  const lines: string[] = [];

  lines.push('# Benchmark — Shield');
  lines.push('');
  lines.push('**Generated by `npm run benchmark`. Do not edit by hand.**');
  lines.push('');
  lines.push(
    'Measures SIH metric 2 (recall and precision of PII detection) and metric 3 ' +
      '(precision of redaction) against a hand-labelled corpus. Labels describe ' +
      'the PAGE, never the detector output — several are things the DOM path ' +
      'structurally cannot see, and they are counted as misses because they are.',
  );
  lines.push('');
  lines.push(`Last run: ${new Date().toISOString()}`);
  lines.push('');

  lines.push('## Headline');
  lines.push('');
  lines.push('| Measure | Value |');
  lines.push('|---|---|');
  lines.push(`| Pages | ${overall.pages} |`);
  lines.push(`| Sensitive elements labelled | ${overall.expected} |`);
  lines.push(`| **Recall** | **${percent(overall.recall)}** |`);
  lines.push(`| **Precision** | **${percent(overall.precision)}** |`);
  lines.push(`| F1 | ${percent(overall.f1)} |`);
  lines.push(`| Category accuracy | ${percent(overall.categoryAccuracy)} |`);
  lines.push(`| Missed | ${overall.missed} |`);
  lines.push(`| Over-flagged | ${overall.overFlagged} |`);
  lines.push(`| Redaction coverage | ${percent(overall.coverage)} |`);
  lines.push(`| **Redaction precision** | **${percent(overall.redactionPrecision)}** |`);
  lines.push(`| Area painted / area needed | ${ratio(overall.areaRatio)} |`);
  lines.push('');
  lines.push(
    'Coverage is the share of sensitive AREA painted — but a blanket blur also ' +
      'scores 100% there, so it is never quoted alone. **Redaction precision** is ' +
      'what metric 3 asks: of everything covered, how much needed covering. A ' +
      'blanket blur scores near zero. The area ratio is signed — above 1.00x means ' +
      'more was painted than needed, below means some was left visible.',
  );
  lines.push('');

  lines.push('## Where the pages come from');
  lines.push('');
  lines.push('| Source | Pages | What that means |');
  lines.push('|---|---|---|');
  const MEANING: Record<string, string> = {
    fixture: 'Test screens, written to exercise our own code.',
    synthetic:
      'Written from what a real page of that kind carries, in the field-naming ' +
      'conventions those portals use - but authored here.',
    real: 'Captured from a page nobody here wrote.',
  };
  for (const row of sourceCounts()) {
    lines.push(`| ${row.source} | ${row.pages} | ${MEANING[row.source] ?? ''} |`);
  }
  lines.push('');

  const realPages = sourceCounts().find((row) => row.source === 'real')?.pages ?? 0;
  if (realPages === 0) {
    lines.push(
      '**No page in this corpus was written by anybody outside this project.** ' +
        'Every number above is a measurement against our own description of what ' +
        'these pages contain. That is a real limit on what they prove, it is the ' +
        'reason this column is printed, and closing it is the remaining half of ' +
        'TASKS.md T1.1.',
    );
    lines.push('');
  }

  if (captureProblems.length > 0) {
    lines.push('Captured files that could not be scored:');
    lines.push('');
    for (const problem of captureProblems) {
      lines.push(`- \`${problem.file}\` - ${problem.why}`);
    }
    lines.push('');
  }

  lines.push('## The pixel layer');
  lines.push('');
  lines.push(
    'What is printed inside an image, scored against boxes measured on the ' +
      'document rather than against element labels. An element label cannot ' +
      'express this: the element is the whole card, so it cannot tell covering ' +
      'the number apart from painting over the entire image, and that difference ' +
      'is what metric 3 asks about.',
  );
  lines.push('');

  const pixel = report.pixelSummary;
  if (pixel.surfaces === 0) {
    lines.push('No document surface was scored in this run.');
  } else {
    lines.push('| Measure | Value |');
    lines.push('|---|---|');
    lines.push(`| Documents scored | ${pixel.surfaces} |`);
    lines.push(`| Regions labelled | ${pixel.expected} |`);
    lines.push(`| Recall | ${percent(pixel.recall)} |`);
    lines.push(`| Precision | ${percent(pixel.precision)} |`);
    lines.push(`| Category accuracy | ${percent(pixel.categoryAccuracy)} |`);
    lines.push(`| Coverage | ${percent(pixel.coverage)} |`);
    lines.push(`| Redaction precision | ${percent(pixel.redactionPrecision)} |`);
    lines.push('');
    lines.push(
      'A match needs an intersection-over-union of ' +
        `${PIXEL_IOU} against the labelled box, so a rectangle covering the whole ` +
        'card does not count as having found the number on it.',
    );
    lines.push('');
    lines.push('| Document | Labelled | Found | Missed | Over-flagged |');
    lines.push('|---|---|---|---|---|');
    for (const surface of report.pixels) {
      lines.push(
        `| ${surface.id} | ${surface.expected} | ${surface.truePositives} | ` +
          `${surface.missed.length} | ${surface.overFlagged} |`,
      );
    }
    lines.push('');

    const pixelMisses = report.pixels.flatMap((surface) =>
      surface.missed.map((miss) => ({ id: surface.id, ...miss })),
    );
    if (pixelMisses.length > 0) {
      lines.push('| Document | Not found | Should have been |');
      lines.push('|---|---|---|');
      for (const miss of pixelMisses) {
        lines.push(`| ${miss.id} | ${miss.what} | ${miss.category} |`);
      }
      lines.push('');
    }
  }

  lines.push(
    '**This is not a measurement of the recognition engine.** Tesseract needs a ' +
      'browser and cannot run here, so the words above are perfect readings of ' +
      'the committed sample documents. What is measured is everything after the ' +
      'engine - line grouping, the shared classifier, box placement - which lives ' +
      'in this repository and had no measurement at all.',
  );
  lines.push('');

  const unmeasured = unmeasuredPixelPages();
  if (unmeasured.length > 0) {
    lines.push('Labelled in pixels and not yet measured:');
    lines.push('');
    for (const row of unmeasured) {
      lines.push(`- \`${row.id}\` - ${row.boxes} box(es), no reading available.`);
    }
    lines.push('');
  }
  lines.push(
    'Faces carry no boxes here at all. `test-screens/face-a.jpg` and `face-b.png` ' +
      'are deliberately not committed, so a face box would depend on photographs ' +
      'this repository does not contain. Inventing one would be making up the only ' +
      'number in the file nobody could check. Face detection is measured in Chrome ' +
      'and recorded in TASKS.md: 6 of 8, reliable at 110px and above.',
  );
  lines.push('');

  lines.push('## By category');
  lines.push('');
  lines.push('| Category | Labelled | Found | Wrongly claimed | Recall | Precision | F1 |');
  lines.push('|---|---|---|---|---|---|---|');
  for (const row of report.categories) {
    lines.push(
      `| ${row.category} | ${row.expected} | ${row.truePositives} | ` +
        `${row.falsePositives} | ${percent(row.recall)} | ${percent(row.precision)} | ` +
        `${percent(row.f1)} |`,
    );
  }
  lines.push('');
  lines.push(
    'Reported per category because the aggregate hides what matters. A detector ' +
      'that finds every password and no Aadhaar number scores well overall on a ' +
      'corpus of login pages.',
  );
  lines.push('');

  lines.push('## By page');
  lines.push('');
  lines.push('| Page | Source | Labelled | Found | Missed | Over-flagged | Coverage | Redaction precision |');
  lines.push('|---|---|---|---|---|---|---|---|');
  for (const page of report.pages) {
    lines.push(
      `| ${page.id} | ${page.source} | ${page.expected} | ${page.truePositives} | ` +
        `${page.missed.length} | ${page.overFlagged.length} | ${percent(page.coverage)} | ` +
        `${percent(page.redactionPrecision)} |`,
    );
  }
  lines.push('');

  lines.push('## Every miss, by name');
  lines.push('');
  lines.push(
    'A miss is a sensitive field that would have been transmitted. Each is listed ' +
      'individually because each is a specific thing to go and look at — unlike an ' +
      'over-flag, which costs the reasoning model some context and nothing else.',
  );
  lines.push('');

  const anyMisses = report.pages.some((page) => page.missed.length > 0);
  if (!anyMisses) {
    lines.push('None.');
  } else {
    lines.push('| Page | Element | Should have been |');
    lines.push('|---|---|---|');
    for (const page of report.pages) {
      for (const miss of page.missed) {
        lines.push(`| ${page.id} | ${miss.elementId} | ${miss.category} |`);
      }
    }
  }
  lines.push('');

  lines.push('## What this does not measure');
  lines.push('');
  lines.push(
    '- **OCR, faces and the visual layer.** They need a browser and pixel ground ' +
      'truth, not element labels. Any identifier reachable only through pixels ' +
      'appears here as a miss.',
  );
  lines.push(
    '- **Extraction.** `dom-map.ts` needs real layout and a real browser. The ' +
      'element maps here are hand-derived from the fixture markup.',
  );
  lines.push(
    '- **Generalisation.** The corpus source column says how much of this is our ' +
      'own fixtures. Growing the `real` share is TASKS.md T1.1.',
  );
  lines.push('');

  return lines.join('\n');
}

function main(): void {
  const report = build();
  const { overall } = report;

  console.log('');
  console.log('  Shield benchmark — SIH metrics 2 and 3');
  console.log('  ' + '-'.repeat(46));
  console.log(`  pages              ${overall.pages}`);
  console.log(`  labelled           ${overall.expected}`);
  console.log(`  recall             ${percent(overall.recall)}`);
  console.log(`  precision          ${percent(overall.precision)}`);
  console.log(`  f1                 ${percent(overall.f1)}`);
  console.log(`  category accuracy  ${percent(overall.categoryAccuracy)}`);
  console.log(`  coverage           ${percent(overall.coverage)}`);
  console.log(`  redaction prec.    ${percent(overall.redactionPrecision)}`);
  console.log(`  area painted       ${ratio(overall.areaRatio)}`);
  console.log(`  missed             ${overall.missed}`);
  console.log(`  over-flagged       ${overall.overFlagged}`);
  console.log('');
  console.log('  sources            ' + sourceCounts().map((row) => `${row.source} ${row.pages}`).join(', '));

  const pixel = report.pixelSummary;
  if (pixel.surfaces > 0) {
    console.log('');
    console.log(`  pixel documents    ${pixel.surfaces}`);
    console.log(`  pixel regions      ${pixel.expected}`);
    console.log(`  pixel recall       ${percent(pixel.recall)}`);
    console.log(`  pixel precision    ${percent(pixel.precision)}`);
    console.log(`  pixel coverage     ${percent(pixel.coverage)}`);
    console.log(`  pixel redact prec. ${percent(pixel.redactionPrecision)}`);
  }
  console.log('');

  // Loud, every run, for as long as it is true. A corpus written entirely by
  // the people being measured is the single biggest caveat on these numbers.
  if ((sourceCounts().find((row) => row.source === 'real')?.pages ?? 0) === 0) {
    console.log('  NOTE  no page in this corpus came from outside this project');
    console.log('');
  }

  for (const problem of captureProblems) {
    console.log(`  SKIPPED  ${problem.file}  ${problem.why}`);
  }
  if (captureProblems.length > 0) console.log('');

  for (const page of report.pages) {
    for (const miss of page.missed) {
      console.log(`  MISS  ${page.id}  ${miss.elementId}  (${miss.category})`);
    }
  }
  if (overall.missed > 0) console.log('');

  for (const surface of report.pixels) {
    for (const miss of surface.missed) {
      console.log(`  PIXEL MISS  ${surface.id}  ${miss.what}  (${miss.category})`);
    }
  }
  if (report.pixelSummary.missed > 0) console.log('');

  writeFileSync(REPORT_PATH, markdown(report), 'utf8');
  console.log(`  written to docs/BENCHMARK.md`);
  console.log('');
}

main();
